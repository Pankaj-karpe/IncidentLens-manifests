<#
  scripts/seal-secrets.ps1
  Turns the secrets that live in the cluster today into three ENCRYPTED SealedSecrets
  (safe to commit), split by who needs them:
    incidentlens-db-creds        -> postgres, api, worker, migrate job
    incidentlens-api-secrets     -> api only        (login signing key, webhook token)
    incidentlens-worker-secrets  -> worker only     (LLM keys, Slack, GitHub, SMTP)
  Run from the manifests repo root:
    powershell -ExecutionPolicy Bypass -File scripts/seal-secrets.ps1
  Optional: -RotateSecretKey makes a new SECRET_KEY (everyone has to log in again).
#>
param(
  [string]$Namespace = "incidentlens-dev",
  [string]$OldSecret = "incidentlens-secrets",
  [string]$OutFile   = "deploy/overlays/dev/sealed-secrets.yaml",
  [switch]$RotateSecretKey
)

if (-not (Get-Command kubeseal -ErrorAction SilentlyContinue)) { throw "kubeseal not found in PATH (step A2)" }
if (-not (Get-Command kubectl  -ErrorAction SilentlyContinue)) { throw "kubectl not found in PATH" }

# --- 1. read today's values from the cluster ---------------------------------------
$raw = (kubectl get secret $OldSecret -n $Namespace -o json) -join "`n"
if ($LASTEXITCODE -ne 0 -or -not $raw) { throw "Could not read secret '$OldSecret' in namespace '$Namespace'" }
$old = @{}
foreach ($p in ($raw | ConvertFrom-Json).data.PSObject.Properties) {
  # Kubernetes stores values base64 encoded: decode them back to text
  $old[$p.Name] = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($p.Value))
}

if ($RotateSecretKey) {
  $bytes = New-Object byte[] 32
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  $old["SECRET_KEY"] = -join ($bytes | ForEach-Object { $_.ToString("x2") })   # 64 hex characters
  Write-Host "SECRET_KEY rotated"
}

# --- 2. decide who gets what ----------------------------------------------------------
$groups = [ordered]@{
  "incidentlens-db-creds"       = @("POSTGRES_PASSWORD", "DATABASE_URL", "ALEMBIC_URL")
  "incidentlens-api-secrets"    = @("SECRET_KEY", "WEBHOOK_TOKEN")
  "incidentlens-worker-secrets" = @("LLM_API_KEY", "EMBEDDING_API_KEY", "SLACK_WEBHOOK_URL", "GITHUB_TOKEN", "SMTP_USER", "SMTP_PASSWORD")
}
foreach ($k in @("POSTGRES_PASSWORD", "DATABASE_URL", "ALEMBIC_URL", "SECRET_KEY", "WEBHOOK_TOKEN")) {
  if (-not $old[$k]) { throw "Required key '$k' is missing from '$OldSecret'" }
}
# Warn about anything in the old secret that would be silently dropped
$mapped   = @($groups.Values | ForEach-Object { $_ })
$unmapped = @($old.Keys | Where-Object { $mapped -notcontains $_ })
if ($unmapped.Count -gt 0) { Write-Warning ("NOT carried over: " + ($unmapped -join ", ")) }

# --- 3. encrypt each group with the cluster's public key ------------------------------
$docs = @()
foreach ($name in $groups.Keys) {
  $a = @("create", "secret", "generic", $name, "--namespace", $Namespace, "--dry-run=client", "-o", "yaml")
  $used = @()
  foreach ($k in $groups[$name]) {
    if ($old[$k]) { $a += "--from-literal=$k=$($old[$k])"; $used += $k }   # optional keys are skipped when empty
  }
  $plain = & kubectl @a                       # builds the plain Secret YAML in memory only (--dry-run)
  if ($LASTEXITCODE -ne 0) { throw "kubectl failed while preparing $name" }
  $sealed = $plain | & kubeseal --format yaml --namespace $Namespace --controller-name sealed-secrets-controller --controller-namespace kube-system
  if ($LASTEXITCODE -ne 0) { throw "kubeseal failed for $name (is the controller running?)" }
  $docs += ($sealed -join "`n")
  Write-Host ("sealed {0}: {1}" -f $name, ($used -join ", "))     # key NAMES only, never values
}

# --- 4. write the file (ASCII: the output is only base64 text) ------------------------
$header = "# GENERATED by scripts/seal-secrets.ps1 - encrypted, safe to commit.`n# Only the sealed-secrets controller of the cluster that created it can decrypt it.`n"
Set-Content -Path $OutFile -Value ($header + ($docs -join "`n---`n") + "`n") -Encoding ascii
Write-Host "written: $OutFile"